"""python paper/tools/make_jes_bst.py <unsrtnat.bst> paper/manuscript_overleaf/jes.bst

jes.bst: unsrtnat.bst with the reference layout of published JES articles,
    A. B. Author, C. Author, and D. Author, ``Title.'' J. Electrochem. Soc., 166, A3031 (2019).
(initials, every author, quoted title, CAS journal abbreviation, volume, first page or article number, year)."""
import os
import sys

src, out = sys.argv[1], sys.argv[2]
s = open(src, encoding="utf-8").read()

ABBREV = [
    ("ACS Applied Energy Materials", "ACS Appl. Energy Mater."),
    ("Advanced Energy Materials", "Adv. Energy Mater."),
    ("Advanced Materials", "Adv. Mater."),
    ("Advanced Science", "Adv. Sci."),
    ("Batteries \\& Supercaps", "Batteries Supercaps"),
    ("Chemical Reviews", "Chem. Rev."),
    ("Communications Chemistry", "Commun. Chem."),
    ("Electrochemical and Solid-State Letters", "Electrochem. Solid-State Lett."),
    ("Electrochimica Acta", "Electrochim. Acta"),
    ("Energy \\& Environmental Science", "Energy Environ. Sci."),
    ("International Journal of Fatigue", "Int. J. Fatigue"),
    ("International Materials Reviews", "Int. Mater. Rev."),
    ("Journal of Applied Mechanics", "J. Appl. Mech."),
    ("Journal of Energy Storage", "J. Energy Storage"),
    ("Journal of Open Research Software", "J. Open Res. Softw."),
    ("Journal of Open Source Software", "J. Open Source Softw."),
    ("Journal of Power Sources", "J. Power Sources"),
    ("Journal of Solid State Electrochemistry", "J. Solid State Electrochem."),
    ("Journal of The Electrochemical Society", "J. Electrochem. Soc."),
    ("Journal of the American Ceramic Society", "J. Am. Ceram. Soc."),
    ("Journal of the Mechanics and Physics of Solids", "J. Mech. Phys. Solids"),
    ("Physical Chemistry Chemical Physics", "Phys. Chem. Chem. Phys."),
    ("Reviews of Modern Physics", "Rev. Mod. Phys."),
    ("SIAM Journal on Applied Mathematics", "SIAM J. Appl. Math."),
    ("Transactions of the ASME", "Trans. ASME"),
]  # names not listed (Joule, Energies, ACS Nano, ChemSusChem, ...) are printed as they are


def rep(a, b):
    global s
    assert s.count(a) == 1, a[:50]
    s = s.replace(a, b)


header = ("%% jes.bst -- unsrtnat.bst (P. W. Daly, LPPL) changed to the reference layout of published\n"
          "%% Journal of The Electrochemical Society articles:\n"
          "%%   A. B. Author, C. Author, and D. Author, ``Title.'' J. Electrochem. Soc., 166, A3031 (2019).\n"
          "%% Only the article and misc entry types are changed. Generated by paper/tools/make_jes_bst.py (code repository).\n")
s = header + s
rep("    doi\n    eid\n", "    doi\n    eid\n    eprint\n")
# initials
rep('"{ff~}{vv~}{ll}{, jj}" format.name$', '"{f.~}{vv~}{ll}{, jj}" format.name$')

jes = ["FUNCTION {jes.journal}", "{ journal 's :="]
for full, ab in ABBREV:
    jes.append(f'  s "{full}" = {{ "{ab}" \'s := }} \'skip$ if$')
jes += ["  s", "}", "",
        "FUNCTION {jes.first.page}",
        "{ pages 't :=",
        '  ""',
        '    { t empty$ not  t #1 #1 substring$ "-" = not  and }',
        "    { t #1 #1 substring$ *  t #2 global.max$ substring$ 't := }",
        "  while$",
        "}", "",
        "FUNCTION {jes.head}",
        "{ format.authors",
        "  title empty$",
        "    'skip$",
        "    { \", ``\" * title add.period$ * \"''\" * }",
        "  if$",
        "}", "",
        "FUNCTION {jes.year}",
        "{ year empty$",
        '    { "empty year in " cite$ * warning$ "" }',
        '    { " (" year * ")" * }',
        "  if$",
        "}", "",
        "FUNCTION {article}",
        "{ output.bibitem pop$",
        "  jes.head",
        '  " " * jes.journal *',
        "  volume empty$ 'skip$ { \", \" * volume * } if$",
        "  pages empty$ 'skip$ { \", \" * jes.first.page * } if$",
        "  jes.year * \".\" *",
        "  write$ newline$",
        "}", "",
        "FUNCTION {misc}",
        "{ output.bibitem pop$",
        "  jes.head",
        "  eprint empty$",
        "    { howpublished empty$ 'skip$ { \" \" * howpublished * } if$ }",
        "    { \" arXiv:\" * eprint * }",
        "  if$",
        "  jes.year * \".\" *",
        "  write$ newline$",
        "}", ""]
jes = "\n".join(jes)

# replace the article and misc functions of unsrtnat
a = s.index("FUNCTION {article}")
b = s.index("FUNCTION {book}")
s = s[:a] + "%% article: see jes.journal below\n\n" + s[b:]
a = s.index("FUNCTION {misc}")
b = s.index("FUNCTION {phdthesis}")
s = s[:a] + s[b:]
rep("FUNCTION {default.type} { misc }", jes + "\nFUNCTION {default.type} { misc }")
open(out, "w", encoding="utf-8", newline="\n").write(s)
print("ok", out)
